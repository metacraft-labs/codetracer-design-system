// build-color-doc.mjs — writes docs/foundations/color.md from mapped/alias/brand.
//
// The colour guide is GENERATED so it can never drift from the tokens: every
// row's "use it for" text is the token's $description (written in Figma), and
// the Dark/Light hex values are resolved through alias → brand. Hand edits to
// color.md are lost; change the description in Figma, re-export, re-run:
//
//   node scripts/build-color-doc.mjs            # write docs/foundations/color.md
//   node scripts/build-color-doc.mjs --check    # exit 1 if color.md is stale
//
// build-color-doc.test.mjs runs --check, so a stale guide fails `node --test`.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = dirname(dirname(fileURLToPath(import.meta.url)));
const OUT = join(REPO, 'docs', 'foundations', 'color.md');
const load = (c) => JSON.parse(readFileSync(join(REPO, c, `${c}.json`), 'utf8'));

// Every token leaf, keyed by dotted path.
function leaves(o, path = [], acc = new Map()) {
  if (o && typeof o === 'object' && '$value' in o) { acc.set(path.join('.'), o); return acc; }
  if (o && typeof o === 'object') for (const [k, v] of Object.entries(o)) if (!k.startsWith('$')) leaves(v, [...path, k], acc);
  return acc;
}

/** Resolve a mapped colour token to a hex in one mode, through alias and brand. */
export function resolver(mapped, alias, brand) {
  // mapped → alias → brand. A reference resolves in its own layer or a lower
  // one, never in a higher one, and never to the token it came from: alias
  // `colors/base/white` points at brand `colors/base/white` (same name).
  const layers = [leaves(mapped), leaves(alias), leaves(brand)];
  return function resolve(value, mode, layer = 0, from = null, depth = 0) {
    if (depth > 10) throw new Error(`reference loop at ${value}`);
    const m = typeof value === 'string' && value.match(/^\{(.+)\}$/);
    if (!m) return value;
    for (let j = layer; j < layers.length; j++) {
      const t = layers[j].get(m[1]);
      if (!t || t === from) continue;
      const next = t.$extensions?.modes?.[mode] ?? t.$value;
      return resolve(next, mode, j, t, depth + 1);
    }
    throw new Error(`unresolved reference ${value}`);
  };
}

// Descriptions repeat a group sentence ("Border and outline colour. …"). Pull
// the sentences every token in a section shares into the section intro.
const sentences = (d) => (d || '').match(/[^.]+(?:\.(?=\s|$)|$)/g)?.map(s => s.trim()).filter(Boolean) ?? [];
function splitShared(descs) {
  const lists = descs.map(sentences);
  const shared = [];
  // A one-token section keeps its whole description. Otherwise take leading
  // sentences that every token shares, leaving each token at least one of its own.
  if (lists.length > 1) {
    for (let i = 0; ; i++) {
      const s = lists[0][i];
      if (s === undefined || !lists.every(l => l.length > i + 1 && l[i] === s)) break;
      shared.push(s);
    }
  }
  return { shared: shared.join(' '), rest: lists.map(l => l.slice(shared.length).join(' ')) };
}

const SECTIONS = [
  ['colors.ui.surface', 'Surfaces', 'Fills behind content. `base` is the fixed structure of a screen (no hover); `primary` is anything the user can act on (has hover and disabled steps); `on-color` is an inverted block; `input` is form fields; `action` is the brand fill of the primary button; `alert` fills status banners.'],
  ['colors.ui.text', 'Text', 'Pick by the ground the text sits on: `primary` on normal surfaces, `on-color` on inverted surfaces, `on-action` on the brand fill. Status colours only for status.'],
  ['colors.ui.icon', 'Icons', 'Icons take these through `button-icon()` / `mask-icon()`, so hover, disabled and both themes follow automatically (D-38).'],
  ['colors.ui.border', 'Borders', 'Outlines of controls and containers. `focus` is the keyboard focus ring only.'],
  ['colors.ui.divider', 'Dividers', 'Rules between sections or rows: lighter than a border.'],
  ['colors.ui.role', 'Agent roles', 'Identify which agent a session belongs to. Never status.'],
  ['colors.ui.chart', 'Charts', 'Series accents, in order.'],
  ['colors.editor', 'Code editor', 'Only inside the code editor and code views. The desktop paints Monaco from its own theme files; these tokens are the design-system side of that theme.'],
];

export function buildColorDoc() {
  const mapped = load('mapped'), alias = load('alias'), brand = load('brand');
  const resolve = resolver(mapped, alias, brand);
  const all = [...leaves(mapped)].filter(([, t]) => t.$type === 'color');
  const used = new Set();
  const out = [];
  out.push('# Colour', '');
  out.push('> GENERATED by `scripts/build-color-doc.mjs` from `mapped/mapped.json`. Do not edit:');
  out.push('> change the token or its description in Figma, re-export, and re-run the script.');
  out.push('');
  out.push('## How to choose a colour', '');
  out.push('1. Only use `colors/ui/*` and `colors/editor/*` (this page). `alias` and `brand` are');
  out.push('   building blocks: never use a ramp step such as `colors-blue-500` in a component.');
  out.push('2. In the app, a token `colors/ui/text/primary/body` is the stylus variable');
  out.push('   `colors-ui-text-primary-body`. It already switches between Dark and Light.');
  out.push('3. Pick the **group** by what you are painting (surface, text, icon, border), then the');
  out.push('   **ramp** by the ground underneath, then the **step** by state.');
  out.push('4. Steps: `default` / `primary` is the resting step, `-hover` its hover, `secondary` and');
  out.push('   `tertiary` are one and two steps further from the ground, `subtle` is quieter,');
  out.push('   `disabled` is the disabled state. A disabled control keeps its fill (D-20).');
  out.push('5. Nothing fits? Don\'t write a hex value and don\'t borrow a status colour. Ask Nikolay.');
  out.push('');
  for (const [prefix, title, intro] of SECTIONS) {
    const rows = all.filter(([p]) => p.startsWith(prefix + '.'));
    if (!rows.length) continue;
    out.push(`## ${title}`, '', intro, '');
    // Sub-sections by the next path level (e.g. surface/base, surface/primary).
    const groups = new Map();
    for (const [p, t] of rows) {
      const rel = p.slice(prefix.length + 1).split('.');
      const key = rel.length > 1 ? rel[0] : '';
      if (!groups.has(key)) groups.set(key, []);
      groups.get(key).push([p, t]);
    }
    for (const [key, items] of groups) {
      const { shared, rest } = splitShared(items.map(([, t]) => t.$description));
      if (key) out.push(`### ${title}: ${key}`, '');
      if (shared) out.push(shared, '');
      out.push('| Token (stylus variable) | Use it for | Dark | Light |', '|---|---|---|---|');
      items.forEach(([p, t], i) => {
        used.add(p);
        const dark = resolve(t.$extensions?.modes?.Dark ?? t.$value, 'Dark');
        const light = resolve(t.$extensions?.modes?.Light ?? t.$value, 'Light');
        const name = '`' + p.replaceAll('.', '-').toLowerCase() + '`';
        const use = (rest[i] || '').replaceAll('|', '\\|') || '—';
        out.push(`| ${name} | ${use} | \`${dark}\` | \`${light}\` |`);
      });
      out.push('');
    }
  }
  const missed = all.filter(([p]) => !used.has(p)).map(([p]) => p);
  if (missed.length) throw new Error('colour tokens with no section in build-color-doc.mjs: ' + missed.join(', '));
  return out.join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const doc = buildColorDoc();
  if (process.argv.includes('--check')) {
    let cur = '';
    try { cur = readFileSync(OUT, 'utf8'); } catch {}
    if (cur !== doc) { console.error('docs/foundations/color.md is stale: run node scripts/build-color-doc.mjs'); process.exit(1); }
    console.log('color.md is up to date');
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, doc);
    console.log('wrote docs/foundations/color.md');
  }
}
